import java.util.*;

/**
 * Good-move bonuses (DESIGN.md): coins the player earns for playing well.
 * Detected on the player's real moves only, never during AI search.
 */
public final class MoveBonuses {
    private MoveBonuses() {}

    public static final int CHECK = 2;
    public static final int FORK = 4;
    public static final int TRADE_UP = 3;
    public static final int PROMOTION = 3;
    public static final int EN_PASSANT = 3;
    public static final int CARD_CAPTURE = 3;

    /** One earned bonus, e.g. "Fork +4". */
    public static class Bonus {
        public final String name;
        public final int coins;

        public Bonus(String name, int coins) {
            this.name = name;
            this.coins = coins;
        }

        @Override
        public String toString() {
            return name + " +" + coins;
        }
    }

    /**
     * Bonuses for a White move.
     * @param before the position before the move (White to move)
     * @param move   the move as generated by the engine (flags set)
     * @param after  the position after the move
     */
    public static List<Bonus> detect(GameState before, Move move, GameState after) {
        List<Bonus> bonuses = new ArrayList<>();
        Piece mover = before.board[move.fromRow][move.fromCol];
        if (mover == null || !mover.isWhite()) return bonuses;

        Piece victim;
        if (move.isSniperShot) victim = before.board[move.sniperTargetRow][move.sniperTargetCol];
        else if (move.isEnPassant) victim = before.board[move.fromRow][move.toCol];
        else victim = before.board[move.toRow][move.toCol];
        boolean captured = victim != null && wasRemoved(before, after, move);

        ChessEngine afterEngine = new ChessEngine(after);
        if (afterEngine.isKingInCheck(after, false)) {
            bonuses.add(new Bonus("Check", CHECK));
        }
        if (isFork(after, afterEngine, move)) {
            bonuses.add(new Bonus("Fork", FORK));
        }
        if (captured && Economy.material(victim) > Economy.material(mover) && !(mover instanceof King)) {
            bonuses.add(new Bonus("Trade up", TRADE_UP));
        }
        if (move.isPromotion) {
            bonuses.add(new Bonus("Promotion", PROMOTION));
        }
        if (move.isEnPassant) {
            bonuses.add(new Bonus("En passant", EN_PASSANT));
        }
        if (captured && isCardMove(before, move, mover)) {
            bonuses.add(new Bonus("Card capture", CARD_CAPTURE));
        }
        return bonuses;
    }

    /** The victim is really gone (a card such as Heavy Armor may have turned the hit into a stun). */
    private static boolean wasRemoved(GameState before, GameState after, Move move) {
        if (move.isSniperShot) return after.board[move.sniperTargetRow][move.sniperTargetCol] == null;
        if (move.isEnPassant) return after.board[move.fromRow][move.toCol] == null;
        Piece now = after.board[move.toRow][move.toCol];
        return now == null || now.isWhite();
    }

    /** After the move, the moved piece attacks two valuable targets (pieces worth 3+, or the King). */
    private static boolean isFork(GameState after, ChessEngine engine, Move move) {
        int r = move.isSniperShot ? move.fromRow : move.toRow;
        int c = move.isSniperShot ? move.fromCol : move.toCol;
        Piece p = after.board[r][c];
        if (p == null || !p.isWhite()) return false;
        int targets = 0;
        for (int tr = 0; tr < 8; tr++) {
            for (int tc = 0; tc < 8; tc++) {
                Piece t = after.board[tr][tc];
                if (t == null || t.isWhite()) continue;
                if ((t instanceof King || Economy.material(t) >= 3) && engine.pieceAttacks(after, r, c, tr, tc)) {
                    targets++;
                }
            }
        }
        return targets >= 2;
    }

    /** The move only exists because of a card (sniper shot, vault, cavalry radius...). */
    private static boolean isCardMove(GameState before, Move move, Piece mover) {
        if (move.isSniperShot) return true;
        GameState plain = before.copy();
        plain.cardManager = new CardManager();
        for (Move m : mover.generateLegalMoves(move.fromRow, move.fromCol, new ChessEngine(plain))) {
            if (m.toRow == move.toRow && m.toCol == move.toCol) return false;
        }
        return true;
    }
}
